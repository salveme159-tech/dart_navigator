const read=file=>fs.readFileSync(path.join(root,file),'utf8');
if(!read('server/_core/index.ts').includes('registerUserAgentRoutes(app, askDart);'))throw new Error('에이전트 연결 경로가 서버에 등록되지 않았습니다.');
